#!/usr/bin/env bash
# =============================================================================
# One-time setup of an OCI VM (Ubuntu 24.04 or Oracle Linux 8/9, x86_64) for gencorr.
# Run ON THE VM:  sudo bash bootstrap_vm.sh [block-device | none]
#
#   * mounts the block volume at /data (formats it only if it is empty)
#   * Docker with its image store on /data/docker
#   * Java 21 + Nextflow (same version as the development machine)
#   * writes /data/gencorr_vm.config with this VM's CPU/memory limits
#
# Safe to re-run (e.g. after resizing the VM: the limits file is regenerated).
# =============================================================================
set -euo pipefail

DEVICE=${1:-/dev/oracleoci/oraclevdb}   # consistent device path chosen at attach time
MOUNT=/data
NXF_VER=26.10.5
RUN_USER=${SUDO_USER:-$(id -un 1000)}   # ubuntu on Ubuntu, opc on Oracle Linux

[[ $(id -u) -eq 0 ]] || { echo "run with sudo" >&2; exit 1; }
[[ $(uname -m) == x86_64 ]] || { echo "gencorr images are amd64: use an x86 shape (E4/E5 Flex), not Ampere" >&2; exit 1; }

# ---------------------------------------------------------------- volume --
if [[ -b $DEVICE ]]; then
    if ! blkid "$DEVICE" >/dev/null 2>&1; then
        echo "formatting empty volume $DEVICE as ext4"
        mkfs.ext4 -q -L gencorr-data "$DEVICE"
    fi
    mkdir -p "$MOUNT"
    if ! grep -q " $MOUNT " /etc/fstab; then
        echo "LABEL=gencorr-data $MOUNT ext4 defaults,_netdev,nofail 0 2" >> /etc/fstab
    fi
    mountpoint -q "$MOUNT" || mount "$MOUNT"
elif [[ $DEVICE == none ]]; then
    echo "no data volume: using the boot volume for $MOUNT" >&2
    mkdir -p "$MOUNT"
else
    echo "ERROR: $DEVICE not found. Attach the block volume (Paravirtualized, device path" >&2
    echo "$DEVICE) and re-run, or run 'sudo bash bootstrap_vm.sh none' to use the boot volume." >&2
    exit 1
fi
mkdir -p "$MOUNT"/{refs,work,results,input,nxf_home,gwascatalog_cache}
chown "$RUN_USER":"$RUN_USER" "$MOUNT"    # runs start here (Nextflow writes .nextflow/)
chown -R "$RUN_USER":"$RUN_USER" "$MOUNT"/{refs,work,results,input,nxf_home,gwascatalog_cache}

# -------------------------------------------------------------- packages --
if command -v apt-get >/dev/null; then            # Ubuntu
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -q
    apt-get install -y -q docker.io openjdk-21-jre-headless rsync unzip tmux curl
elif command -v dnf >/dev/null; then              # Oracle Linux 8/9
    dnf install -y -q dnf-plugins-core
    dnf config-manager --add-repo https://download.docker.com/linux/rhel/docker-ce.repo
    # --allowerasing: replaces the podman/runc packages Oracle Linux ships with
    dnf install -y -q --allowerasing docker-ce docker-ce-cli containerd.io \
        java-21-openjdk-headless rsync unzip tmux curl
else
    echo "unsupported distribution (need apt or dnf)" >&2; exit 1
fi

mkdir -p /etc/docker "$MOUNT/docker"
cat > /etc/docker/daemon.json <<EOF
{ "data-root": "$MOUNT/docker" }
EOF
systemctl enable docker
systemctl restart docker
usermod -aG docker "$RUN_USER"

# -------------------------------------------------------------- nextflow --
# The launcher script from the release; it downloads the matching runtime into
# NXF_HOME on first use (done here as the run user, so the files are theirs).
curl -fsSL "https://github.com/nextflow-io/nextflow/releases/download/v$NXF_VER/nextflow" \
    -o /usr/local/bin/nextflow
chmod 755 /usr/local/bin/nextflow
chown -R "$RUN_USER":"$RUN_USER" "$MOUNT/nxf_home"
sudo -u "$RUN_USER" env NXF_VER="$NXF_VER" NXF_HOME="$MOUNT/nxf_home" TERM=dumb \
    /usr/local/bin/nextflow -v

profile=/home/$RUN_USER/.bashrc
grep -q 'gencorr VM' "$profile" || cat >> "$profile" <<EOF

# gencorr VM
export NXF_VER=$NXF_VER
export NXF_HOME=$MOUNT/nxf_home
export NXF_OPTS='-Xms1g -Xmx4g'
EOF
chown -R "$RUN_USER":"$RUN_USER" "$MOUNT/nxf_home"

# ------------------------------------------------- limits for this shape --
cpus=$(nproc)
mem_gb=$(free -g | awk '/^Mem:/ {print $2}')
usable=$(( mem_gb - 4 ))          # leave room for the OS, Docker and Nextflow
cat > "$MOUNT/gencorr_vm.config" <<EOF
// Generated by bootstrap_vm.sh for this VM ($cpus vCPUs, ${mem_gb} GB). Re-run after a resize.
includeConfig '/home/$RUN_USER/gencorr/cloud/oci/oci.config'
process.resourceLimits = [ cpus: $cpus, memory: ${usable}.GB, time: 72.h ]
executor.cpus   = $cpus
executor.memory = '${usable} GB'
EOF
chown "$RUN_USER":"$RUN_USER" "$MOUNT/gencorr_vm.config"

echo
echo "Done: $cpus vCPUs, ${mem_gb} GB RAM, data on $MOUNT ($(df -h --output=avail "$MOUNT" | tail -1) free)."
echo "Log out and back in (docker group), then run cloud/oci/push_to_vm.sh from your machine."
